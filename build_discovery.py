#!/usr/bin/env python3
"""Build discovery assets from an explicit list of discoverable static profiles.

Run after changing herbs.json or discovery-profiles.json. Inclusion is not
a clinical review; source-check status is displayed on each profile.
"""
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def catalogue(root=ROOT):
    records = json.loads((root / 'herbs.json').read_text())
    ids = json.loads((root / 'discovery-profiles.json').read_text())
    by_id = {herb['id']: herb for herb in records}
    if not ids or len(ids) != len(set(ids)) or len(by_id) != len(records):
        raise ValueError('Missing or duplicate herb IDs')
    result = []
    for herb_id in ids:
        herb = by_id[herb_id]  # Fail rather than silently dropping a published profile.
        if not (root / 'herbs' / (herb_id + '.html')).is_file():
            raise ValueError(f'Missing profile file: {herb_id}')
        result.append(dict(id=herb_id, name=herb['name'], scientific=herb['scientific'],
                           url='/herbs/' + herb_id))
    return sorted(result, key=lambda herb: herb['name'].casefold())


def render_cards(herbs):
    return '\n'.join(
        f'                    <a class="herb-card" href="{escape(h["url"], quote=True)}" '
        f'data-name="{escape(h["name"], quote=True)}" data-scientific="{escape(h["scientific"], quote=True)}">\n'
        f'                        <h2 class="herb-card__name">{escape(h["name"])}</h2>\n'
        f'                        <p class="herb-card__scientific"><em>{escape(h["scientific"])}</em></p>\n'
        '                    </a>' for h in herbs)


def build(root=ROOT):
    herbs = catalogue(root)
    # External script: escape '<' to remain safe if embedded by a future consumer.
    index = json.dumps(herbs, ensure_ascii=True, indent=2).replace('<', '\\u003c')
    (root / 'herb-search-index.js').write_text(
        '// Generated by build_discovery.py; do not edit.\nwindow.HerbCraftSearchIndex = ' + index + ';\n')
    for path in ('herb-directory.html', 'herb-directory/index.html'):
        file = root / path
        html = file.read_text()
        html, count = re.subn(r'<!-- HERB_CARDS_START -->.*?<!-- HERB_CARDS_END -->',
            lambda _: '<!-- HERB_CARDS_START -->\n' + render_cards(herbs) + '\n                <!-- HERB_CARDS_END -->',
            html, flags=re.S)
        if count != 1:
            raise ValueError(f'Expected one card region in {path}')
        html = re.sub(r'(<p id="search-results-message"[^>]*>).*?(</p>)',
                      lambda m: m[1] + f'{len(herbs)} herb profiles' + m[2], html)
        file.write_text(html)
    return len(herbs)


if __name__ == '__main__':
    print(f'Built discovery assets for {build()} supported herb profiles.')
